/* Build a SQL Editor bootstrap from db/migrations/*.sql.

   Does not connect to a database. Does not read .env files. Output is
   `.tmp/supabase-bootstrap.sql` (gitignored).

   Usage:  node scripts/generate-supabase-bootstrap.js */

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { checksum } from '../db/migration-checksum.js'

const MIGRATIONS_DIR = new URL('../db/migrations/', import.meta.url)
const OUTPUT = new URL('../.tmp/supabase-bootstrap.sql', import.meta.url)

const sqlLiteral = (value) => `'${String(value).replace(/'/g, "''")}'`

/** Drop a file-level BEGIN;/COMMIT; pair so the bootstrap can wrap body + stamp. */
export function stripOuterTransaction(sql) {
  const lines = String(sql).replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').split('\n')
  let start = 0
  while (start < lines.length && (lines[start].trim() === '' || lines[start].trimStart().startsWith('--'))) start += 1
  let end = lines.length - 1
  while (end > start && (lines[end].trim() === '' || lines[end].trimStart().startsWith('--'))) end -= 1
  if (
    start < lines.length
    && /^BEGIN\s*;\s*$/i.test(lines[start].trim())
    && /^COMMIT\s*;\s*$/i.test(lines[end].trim())
  ) {
    return [...lines.slice(0, start), ...lines.slice(start + 1, end), ...lines.slice(end + 1)].join('\n')
  }
  return lines.join('\n')
}

export function generateBootstrapSql(files) {
  const header = [
    '-- Generated by scripts/generate-supabase-bootstrap.js. Do not hand-edit.',
    '-- Paste into the Supabase SQL Editor when db/migrate.js cannot connect.',
    '-- No connection strings, API keys, owner emails, or customer rows.',
    '-- Each migration is one transaction: body + schema_migrations stamp.',
    '-- A failure rolls back only the current file; earlier COMMITs remain.',
    '',
    'CREATE TABLE IF NOT EXISTS public.schema_migrations (',
    '  filename text PRIMARY KEY,',
    '  checksum text NOT NULL,',
    '  applied_at timestamptz NOT NULL DEFAULT now()',
    ');',
    '',
  ]

  const blocks = files.map(({ filename, contents }) => {
    const digest = checksum(contents)
    const body = stripOuterTransaction(contents).replace(/\s+$/, '')
    return [
      `-- ${filename}`,
      'BEGIN;',
      body,
      `INSERT INTO public.schema_migrations(filename, checksum) VALUES (${sqlLiteral(filename)}, ${sqlLiteral(digest)});`,
      'COMMIT;',
      '',
    ].join('\n')
  })

  return `${header.join('\n')}${blocks.join('\n')}`
}

export async function loadMigrationFiles(dir = MIGRATIONS_DIR) {
  const names = (await readdir(dir)).filter((name) => name.endsWith('.sql')).sort()
  const files = []
  for (const filename of names) {
    files.push({ filename, contents: await readFile(new URL(filename, dir), 'utf8') })
  }
  return files
}

async function main() {
  const files = await loadMigrationFiles()
  const sql = generateBootstrapSql(files)
  await mkdir(new URL('../.tmp/', import.meta.url), { recursive: true })
  await writeFile(OUTPUT, sql, 'utf8')
  console.log(`wrote ${files.length} migration(s) to .tmp/supabase-bootstrap.sql`)
}

const isEntryPoint = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1].replace(/\\/g, '/')}`).href
if (isEntryPoint) {
  main().catch((error) => { console.error(error.message); process.exit(1) })
}
